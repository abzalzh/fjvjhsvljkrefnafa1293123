"""Rebuild OpenAPI, JSON Schema, TS model types and synthetic API examples."""
import json
import sys
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT/'backend'))
from app.main import create_app
from app.database import load_dataset
from app.schemas.contracts import Dataset, TripPreferences
from app.services.planner.engine import generate


def write_json(path, obj):
    path.parent.mkdir(parents=True,exist_ok=True)
    path.write_text(json.dumps(obj,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')


def ts(schema):
    if '$ref' in schema: return schema['$ref'].split('/')[-1]
    if 'const' in schema: return json.dumps(schema['const'])
    if 'enum' in schema: return ' | '.join(json.dumps(v) for v in schema['enum'])
    if 'anyOf' in schema: return ' | '.join(ts(v) for v in schema['anyOf'])
    kind=schema.get('type')
    if kind=='array': return f'Array<{ts(schema["items"])}>'
    if kind=='object':
        if 'properties' in schema:
            required=set(schema.get('required',[]))
            return '{\n'+'\n'.join(f'  {json.dumps(k)}{"" if k in required else "?"}: {ts(v)};' for k,v in schema['properties'].items())+'\n}'
        extra=schema.get('additionalProperties',{})
        return 'Record<string, '+(ts(extra) if isinstance(extra,dict) else 'unknown')+'>'
    return {'integer':'number','number':'number','string':'string','boolean':'boolean','null':'null'}.get(kind,'unknown')


if __name__=='__main__':
    api=create_app().openapi()
    write_json(ROOT/'docs/openapi.json',api)
    write_json(ROOT/'docs/dataset.schema.json',Dataset.model_json_schema())
    types='// Generated by scripts/export_contract.py. Do not edit. API v1.0.\n'
    types+='\n\n'.join(f'export type {name} = {ts(schema)};' for name,schema in sorted(api['components']['schemas'].items()))+'\n'
    (ROOT/'integration').mkdir(exist_ok=True)
    (ROOT/'integration/api-types.ts').write_text(types,encoding='utf-8')
    prefs=TripPreferences(budget_kzt=70000,days=3,travelers=1,transport='public',interests=['nature'],start_date='2026-11-26')
    data=load_dataset(ROOT/'backend/tests/fixtures/demo')
    write_json(ROOT/'integration/examples/generate-request.json',prefs.model_dump(mode='json'))
    write_json(ROOT/'integration/examples/generate-response.demo.json',generate(data,prefs,True).model_dump(mode='json'))
    write_json(ROOT/'integration/examples/no-results.demo.json',generate(data,prefs.model_copy(update={'budget_kzt':0}),True).model_dump(mode='json'))
    print('Exported OpenAPI, dataset schema, TypeScript types and demo examples.')
